package generate

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"

	"github.com/dragstor/awesome-reliability-tools/internal/favicons"
	"github.com/dragstor/awesome-reliability-tools/internal/render"
	"github.com/dragstor/awesome-reliability-tools/internal/schema"
)

// generatedMarker is embedded in generated artifacts so that hand edits are obvious.
const generatedMarker = "Generated by cmd/generate from data/*.yaml. DO NOT EDIT."

// Normalize builds the website-facing representation of the dataset.
func Normalize(catalog *schema.Catalog, tools []schema.Tool) *schema.NormalizedCatalog {
	var normalized []schema.NormalizedTool
	for _, t := range tools {
		features := make(map[string]schema.NormalizedFeature, len(catalog.Features))
		for _, f := range catalog.Features {
			claim := t.ResolveFeature(f)
			features[f.ID] = schema.NormalizedFeature{
				Value:      claim.Value,
				VerifiedAt: claim.VerifiedAt,
				Sources:    claim.Sources,
				Notes:      claim.Notes,
			}
		}
		normalized = append(normalized, schema.NormalizedTool{
			ID:           t.ID,
			Name:         t.Name,
			Status:       t.Status,
			Homepage:     t.Homepage,
			Description:  t.Description,
			Categories:   t.Categories,
			Deployment:   t.Deployment,
			OpenSource:   t.OpenSource,
			Repository:   t.Repository,
			License:      t.License,
			Features:     features,
			Sources:      t.Sources,
			Notes:        t.Notes,
			LastVerified: t.LastVerified(),
		})
	}
	sort.Slice(normalized, func(i, j int) bool {
		return normalized[i].Name < normalized[j].Name
	})
	return &schema.NormalizedCatalog{
		Note:     generatedMarker,
		Features: catalog.Features,
		Tools:    normalized,
	}
}

// AttachFavicons records the cached favicon filename for each tool, if one is
// present locally. It only reads the filesystem, so it stays deterministic and
// offline; fetching is a separate, explicit command.
func AttachFavicons(catalog *schema.NormalizedCatalog, dir string) {
	for i := range catalog.Tools {
		if name, ok := favicons.Find(dir, catalog.Tools[i].ID); ok {
			catalog.Tools[i].Favicon = name
		}
	}
}

// marshalCatalog renders the normalized catalog as deterministic JSON.
func marshalCatalog(catalog *schema.NormalizedCatalog) ([]byte, error) {
	b, err := json.MarshalIndent(catalog, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encoding catalog JSON: %w", err)
	}
	return append(b, '\n'), nil
}

// WriteJSON writes the normalized catalog to path as deterministic JSON.
func WriteJSON(catalog *schema.NormalizedCatalog, path string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("creating directory for %q: %w", path, err)
	}
	b, err := marshalCatalog(catalog)
	if err != nil {
		return err
	}
	if err := os.WriteFile(path, b, 0o644); err != nil {
		return fmt.Errorf("writing %q: %w", path, err)
	}
	return nil
}

// WriteREADME renders and writes the README.
func WriteREADME(tmplPath, outPath string, catalog *schema.Catalog, tools []schema.Tool) error {
	b, err := render.RenderREADME(tmplPath, catalog, tools)
	if err != nil {
		return err
	}
	if dir := filepath.Dir(outPath); dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return fmt.Errorf("creating directory for %q: %w", outPath, err)
		}
	}
	if err := os.WriteFile(outPath, b, 0o644); err != nil {
		return fmt.Errorf("writing %q: %w", outPath, err)
	}
	return nil
}

// CopyStatic recursively copies a static source directory into a destination.
func CopyStatic(src, dst string) error {
	if err := os.MkdirAll(dst, 0o755); err != nil {
		return err
	}
	return filepath.Walk(src, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		target := filepath.Join(dst, rel)
		if info.IsDir() {
			return os.MkdirAll(target, info.Mode())
		}
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return err
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(target, data, info.Mode())
	})
}

// Options describes the input templates and output locations for generation.
type Options struct {
	ReadmeTmpl string
	ReadmeOut  string
	SiteTmpl   string
	DistDir    string
	SiteDir    string
}

// DefaultOptions returns the paths used by the command line tool.
func DefaultOptions() Options {
	return Options{
		ReadmeTmpl: "templates/README.md.tmpl",
		ReadmeOut:  "README.md",
		SiteTmpl:   "templates/index.html.tmpl",
		DistDir:    "dist",
		SiteDir:    "site",
	}
}

// All runs the full generation pipeline and returns the generated catalog.
func All(catalog *schema.Catalog, tools []schema.Tool, opts Options) (*schema.NormalizedCatalog, error) {
	if err := os.MkdirAll(filepath.Join(opts.DistDir, "data"), 0o755); err != nil {
		return nil, fmt.Errorf("creating output directory: %w", err)
	}

	// Render the README from a stable, sorted view of the dataset.
	sortedTools := make([]schema.Tool, len(tools))
	copy(sortedTools, tools)
	sort.Slice(sortedTools, func(i, j int) bool { return sortedTools[i].Name < sortedTools[j].Name })

	normalized := Normalize(catalog, tools)
	AttachFavicons(normalized, filepath.Join(opts.SiteDir, "assets", "favicons"))

	catalogBytes, err := marshalCatalog(normalized)
	if err != nil {
		return nil, err
	}

	if _, err := os.Stat(opts.SiteDir); err == nil {
		if err := CopyStatic(opts.SiteDir, opts.DistDir); err != nil {
			return nil, fmt.Errorf("copying site assets: %w", err)
		}
	}

	siteHTML, err := render.RenderSite(opts.SiteTmpl, catalogBytes)
	if err != nil {
		return nil, fmt.Errorf("rendering site index: %w", err)
	}
	if err := os.WriteFile(filepath.Join(opts.DistDir, "index.html"), siteHTML, 0o644); err != nil {
		return nil, fmt.Errorf("writing site index: %w", err)
	}

	if err := os.WriteFile(filepath.Join(opts.DistDir, "data", "catalog.json"), catalogBytes, 0o644); err != nil {
		return nil, fmt.Errorf("writing catalog JSON: %w", err)
	}

	if err := WriteREADME(opts.ReadmeTmpl, opts.ReadmeOut, catalog, sortedTools); err != nil {
		return nil, fmt.Errorf("writing README: %w", err)
	}
	return normalized, nil
}
